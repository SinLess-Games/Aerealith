interface SearchEmptyStateProps {
  message: string
  query: string
}

function SearchEmptyState({ message, query }: Readonly<SearchEmptyStateProps>) {
  return (
    <div
      className={cn(
        'flex min-h-48 flex-col items-center justify-center',
        'px-6 py-10 text-center',
      )}
    >
      <span
        aria-hidden='true'
        className={cn(
          'grid size-12 place-items-center rounded-2xl border',
          'border-[var(--ae-border)]',
          'bg-[color-mix(in_srgb,var(--ae-surface)_72%,transparent)]',
          'text-[var(--ae-foreground-muted)]',
        )}
      >
        <SearchOffIcon />
      </span>

      <h3 className='mt-4 text-sm font-semibold text-[var(--ae-foreground)]'>
        No results for “{query}”
      </h3>

      <p className='mt-1 max-w-sm text-sm leading-6 text-[var(--ae-foreground-muted)]'>
        {message}
      </p>
    </div>
  )
}

interface SearchHintProps {
  keys: readonly string[]
  label: string
}

function SearchHint({ keys, label }: Readonly<SearchHintProps>) {
  return (
    <span className='inline-flex items-center gap-1.5'>
      <span className='inline-flex items-center gap-1'>
        {keys.map((key) => (
          <kbd
            key={key}
            className={cn(
              'inline-flex min-h-5 min-w-5 items-center justify-center',
              'rounded border border-[var(--ae-border)] px-1',
              'bg-[var(--ae-surface)] font-mono text-[0.625rem]',
              'text-[var(--ae-foreground-muted)]',
              'shadow-[inset_0_-1px_0_rgba(0,0,0,0.16)]',
            )}
          >
            {key}
          </kbd>
        ))}
      </span>

      <span>{label}</span>
    </span>
  )
}

function ShortcutKeys({ compact }: Readonly<{ compact: boolean }>) {
  return (
    <kbd
      className={cn(
        'hidden shrink-0 items-center gap-1 rounded-md border',
        'border-[var(--ae-border)]',
        'bg-[var(--ae-background)] px-1.5 py-1',
        'font-mono text-[0.625rem] font-medium',
        'text-[var(--ae-foreground-muted)]',
        'shadow-[inset_0_-1px_0_rgba(0,0,0,0.14)] sm:inline-flex',
        compact && 'sm:hidden',
      )}
    >
      <span>Ctrl</span>
      <span>K</span>
    </kbd>
  )
}

function getSearchScopeLabel(audience: DocsAudience | undefined): string {
  if (audience === 'developer') {
    return 'Searching developer documentation'
  }

  if (audience === 'user') {
    return 'Searching user documentation'
  }

  return 'Searching all documentation'
}

function getResultsStatus(query: string, resultCount: number): string {
  if (query.trim().length === 0) {
    return 'Enter a search term'
  }

  if (resultCount === 0) {
    return 'No results'
  }

  return `${resultCount} ${resultCount === 1 ? 'result' : 'results'}`
}

function isEditableTarget(target: EventTarget | null): boolean {
  if (!(target instanceof HTMLElement)) return false

  return (
    target.isContentEditable ||
    target instanceof HTMLInputElement ||
    target instanceof HTMLTextAreaElement ||
    target instanceof HTMLSelectElement
  )
}

